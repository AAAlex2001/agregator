export const OPO_KEYS = Object.keys(TABLE);

export function cell(opo: string, type: ExpertiseType): string[] {
  const row = TABLE[opo];
  if (!row) return [];
  const docs = row["КЛ/ТП"] ?? [];
  if (type === "КЛ/ТП") return docs.length === 1 ? docs : [];
  if (type === "КЛ") return docs.length === 2 ? [docs[0]] : [];
  if (type === "ТП") return docs.length === 2 ? [docs[1]] : [];
  return row[type] ?? [];
}

export function computeBadgeCodes(types: ExpertiseType[], opos: string[]): string[] {
  const seen = new Set<string>();
  const result: string[] = [];
  for (const opo of opos) {
    for (const type of types) {
      for (const code of cell(opo, type)) {
        if (!seen.has(code)) {
          seen.add(code);
          result.push(code);
        }
      }
    }
  }
  return result;
}

"""Что бот пишет пользователю."""

from html import escape

from app.poster.channels.models import PosterChannel

GREETING = (
    "Здравствуйте! Здесь подключаются Telegram-каналы и группы для публикаций с сайта «Ресурс-Плюс».\n\n"
    "Нажмите «Подключить канал» в разделе «Публикации → Каналы и группы» на сайте — "
    "бот откроется по ссылке и привяжет Telegram к вашему аккаунту."
)
LINKED = "Telegram привязан к аккаунту. Выберите канал или группу кнопками ниже — бот добавится туда сам."
LINK_EXPIRED = "Ссылка устарела. Нажмите «Подключить канал» на сайте ещё раз."


def connected(channel: PosterChannel) -> str:
    """Чат подключён и готов к публикациям."""

    return f"✅ «{escape(channel.title)}» подключён. Теперь в него можно публиковать посты с сайта."


def connected_without_rights(channel: PosterChannel) -> str:
    """Чат подключён, но публиковать бот пока не может."""

    return (
        f"«{escape(channel.title)}» подключён, но у бота нет прав на публикацию. "
        "Сделайте бота администратором с правом публиковать сообщения."
    )

def user_message(instruction: str, html: str) -> str:
    """Собирает сообщение для нейросети: просьба автора и текущий текст поста."""
    current_text = html if plain_text(html) else "(пусто)"

    return f"Просьба автора:\n{instruction}\n\nТекущий текст публикации (HTML):\n{current_text}"


def answer_to_html(answer: str) -> str:
    """Превращает ответ нейросети в HTML: убирает обёртку ```html, простой текст делит на абзацы."""
    text = re.sub(r"^```[a-z]*\s*|\s*```$", "", answer.strip())

    if "<" in text:
        return text

    paragraphs = [part.strip() for part in text.split("\n\n") if part.strip()]

    return "".join(f"<p>{escape(paragraph)}</p>" for paragraph in paragraphs)

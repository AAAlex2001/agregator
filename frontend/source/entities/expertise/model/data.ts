export const cell = (opo: string, type: ExpertiseType): string[] => {
  const row = TABLE[opo];
  if (!row) return [];
  const docs = row["КЛ/ТП"] ?? [];
  if (type === "КЛ/ТП") {
    return docs.length === 1 ? docs : [];
  }
  if (type === "КЛ") {
    return docs.length === 2 ? [docs[0]] : [];
  }
  if (type === "ТП") {
    return docs.length === 2 ? [docs[1]] : [];
  }
  return row[type] ?? [];
};

export const computeBadgeCodes = (types: ExpertiseType[], opos: string[]): string[] => {
  const seen = new Set<string>();
  const result: string[] = [];
  for (const o of opos) {
    for (const t of types) {
      for (const code of cell(o, t)) {
        if (!seen.has(code)) {
          seen.add(code);
          result.push(code);
        }
      }
    }
  }
  return result;
};

export const ALL_BADGE_CODES: string[] = computeBadgeCodes(TYPES, Object.keys(TABLE));
export const ALL_BADGE_CODES_SET: ReadonlySet<string> = new Set(ALL_BADGE_CODES);

export const isOpoEnabled = (opo: string, types: ExpertiseType[]) =>
  !types.length || types.some((t) => cell(opo, t).length > 0);

export const isTypeEnabled = (type: ExpertiseType, opos: string[]) =>
  !opos.length || opos.some((o) => cell(o, type).length > 0);

